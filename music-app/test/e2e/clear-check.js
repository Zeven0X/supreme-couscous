const { _electron } = require('playwright'); const fs = require('fs'), path = require('path');
const SP = process.env.SP; // SP/media holds the test songs (made by the developer) const DATA = SP + '/userdata-clear'; fs.rmSync(DATA, { recursive: true, force: true });
let pass = 0, fail = 0; const ok = (n, c, x = '') => { if (c) { pass++; console.log('✓', n, x); } else { fail++; console.log('✗', n, x); } };
(async () => {
  const a = await _electron.launch({ executablePath: 'node_modules/electron/dist/electron', args: ['.', '--no-sandbox', '--force-device-scale-factor=2', '--autoplay-policy=no-user-gesture-required'], env: { ...process.env, TONIX_DATA: DATA } });
  const w = await a.firstWindow(); const errs = []; w.on('pageerror', (e) => errs.push(e.message)); await w.waitForFunction(() => window.__tfReady); await w.setViewportSize({ width: 1320, height: 880 });
  const ev = (f, x) => w.evaluate(f, x), wait = (ms) => w.waitForTimeout(ms), k = (x) => w.keyboard.press(x);
  const media = ['Rainfall.mp3', 'Golden Hour.mp3', 'My Video Clip.mp4'].map((f) => path.join(SP, 'media', f));
  await ev((p) => importPaths(p), media); await wait(500);
  const conv = await ev(() => S.tracks.find((t) => t.isVideo).mediaPath);
  await w.dblclick('.card >> nth=0'); await w.waitForFunction(() => !audio.paused);
  await k('Control+2'); await wait(600); await k('a'); await wait(300); for (const n of [0, 1]) await w.click(`.pick >> nth=${n}`); await w.click('.modal .btn.primary'); await wait(400);
  await k('Control+1'); await wait(400);
  await w.click('#btn-clear-all'); await wait(400);
  await w.locator('.modal').screenshot({ path: SP + '/concepts/clear-all.png' });
  ok('Cancel is focused (Enter does not clear)', await ev(() => document.activeElement.textContent === 'Cancel'));
  await w.click('.modal .btn:has-text("Cancel")'); await wait(200); ok('Cancel keeps songs', (await ev(() => S.tracks.length)) === 3);
  await w.click('#btn-clear-all'); await wait(300); await w.click('.modal .btn.danger'); await wait(800);
  ok('library empty', (await ev(() => S.tracks.length + document.querySelectorAll('#grid .card').length)) === 0);
  ok('playing stopped', await ev(() => audio.paused && !cur()));
  ok('original files still there', media.every((f) => fs.existsSync(f)));
  ok('video copy deleted', !fs.existsSync(conv));
  await k('Control+2'); await wait(600);
  ok('map kept, songs missing', (await ev(() => TFMap.map.stops.length)) === 2);
  await k('Control+1'); await wait(300); await w.click('#btn-clear-all'); await wait(300);
  ok('empty: friendly note, no window', (await ev(() => document.querySelectorAll('.modal').length)) === 0);
  await a.close();
  const a2 = await _electron.launch({ executablePath: 'node_modules/electron/dist/electron', args: ['.', '--no-sandbox'], env: { ...process.env, TONIX_DATA: DATA } });
  const w2 = await a2.firstWindow(); await w2.waitForFunction(() => window.__tfReady);
  ok('still empty after restart', (await w2.evaluate(() => S.tracks.length)) === 0);
  await a2.close();
  console.log(`CLEAR CHECK: ${pass} passed, ${fail} failed, ${errs.length} page errors ${errs.join(' | ')}`);
})().catch((e) => { console.log('FAIL', e.message.split('\n')[0]); process.exit(1); });
